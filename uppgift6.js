"use strict";

function calculateArea(b, h) {      // Beräknar area, och returnerar resultat
    return b * h;                   // basen gånger höjden
}

// tre olika värden för funktionen att hantera.
console.log("Arenan är " + calculateArea(3, 17));
console.log("Arean är " + calculateArea(2, 122));
console.log("Arean är " + calculateArea(8, 7));